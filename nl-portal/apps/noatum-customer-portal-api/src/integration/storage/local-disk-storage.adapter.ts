import { Injectable, Logger } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { createHash } from 'node:crypto';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve, sep } from 'node:path';

import {
  FileStorageAdapter,
  type StoredFileHandle,
  type StoredFileInput,
} from '../../contracts/adapters/file-storage.adapter';

/**
 * Files on the local filesystem, for development and tests.
 *
 * Not a production store: App Service storage is ephemeral and per-instance, so a
 * file written by one instance is invisible to the next and gone at the next
 * restart. Configuration refuses to boot with this selected in production, the
 * same way the development sign-in bypass is refused.
 *
 * This is not the database fallback Q2 forbids. Bytes never enter PostgreSQL; the
 * only thing that changes between here and Azure is which class is bound.
 */
@Injectable()
export class LocalDiskStorageAdapter extends FileStorageAdapter {
  private readonly logger = new Logger(LocalDiskStorageAdapter.name);
  private readonly root: string;

  constructor(config: ConfigService) {
    super();
    this.root = resolve(config.get<string>('storage.localRoot') ?? '.local-storage');
  }

  isConfigured(): boolean {
    return true;
  }

  async put(input: StoredFileInput): Promise<StoredFileHandle> {
    const target = this.pathFor(input);

    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, input.content);

    return { container: input.container, blobName: input.blobName };
  }

  async get(handle: StoredFileHandle): Promise<Buffer | null> {
    try {
      return await readFile(this.pathFor(handle));
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null;
      throw error;
    }
  }

  async delete(handle: StoredFileHandle): Promise<void> {
    // `force` makes an absent file a success rather than a throw, so a retried
    // cleanup does not fail on the second pass.
    await rm(this.pathFor(handle), { force: true });
  }

  /**
   * Resolves the object to a path and proves it stayed inside the root.
   *
   * The name is generated by us, so traversal should be impossible - but "should
   * be" is not a control. A single `..` reaching this method would otherwise
   * write anywhere the process can reach, so the containment is asserted rather
   * than assumed.
   */
  private pathFor(handle: StoredFileHandle): string {
    const container = safeSegment(handle.container);
    const target = resolve(join(this.root, container, handle.blobName));
    const base = join(this.root, container) + sep;

    if (!target.startsWith(base)) {
      this.logger.error(`Refused a storage path outside the root: ${handle.blobName}`);
      throw new Error('Refusing to resolve a storage path outside the container root.');
    }

    return target;
  }
}

/** Containers come from configuration, but this costs nothing and closes the case. */
function safeSegment(value: string): string {
  const cleaned = value.replace(/[^a-z0-9-]/gi, '');
  return cleaned === '' ? 'default' : cleaned;
}

/** Stable across retries, so the same bytes are recognised rather than re-stored. */
export function checksumOf(content: Buffer): string {
  return createHash('sha256').update(content).digest('hex');
}
