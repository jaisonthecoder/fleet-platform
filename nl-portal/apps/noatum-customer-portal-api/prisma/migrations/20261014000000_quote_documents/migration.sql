-- ---------------------------------------------------------------------------
-- Files, and the quote they belong to.
--
-- Two tables rather than one, and the split is the whole design:
--
--   `stored_file` is what we kept - bytes, type, size, checksum, where they are.
--     It knows nothing about quotes, so bookings and claims reuse it untouched.
--   `quote_document` is what it means - which quote, which direction, whether
--     the customer may see it. It carries the tenancy.
--
-- A single polymorphic table was considered and rejected: quote documents are
-- Pattern A, shipment documents are Pattern B through `shipment_visibility`, and
-- one row level security policy cannot express both.
--
-- Bytes never enter PostgreSQL. `blob_name` addresses an object in a container.
-- ---------------------------------------------------------------------------

CREATE TYPE stored_file_scan_status AS ENUM ('pending', 'clean', 'infected', 'skipped');
CREATE TYPE quote_document_direction AS ENUM ('from_customer', 'to_customer');

CREATE TABLE stored_file (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),

  blob_container    varchar(120) NOT NULL,
  -- Generated by the API, never a client filename. That is what makes path
  -- traversal and silent overwriting impossible rather than merely unlikely.
  blob_name         varchar(400) NOT NULL,

  -- Kept for display and for the download filename only. Never used as a path.
  original_filename varchar(200) NOT NULL,
  -- The verified type, decided from the leading bytes, not the browser's claim.
  content_type      varchar(120) NOT NULL,
  size_bytes        integer NOT NULL,
  checksum_sha256   char(64) NOT NULL,

  -- Malware scanning is deferred (21.09.2026), so rows arrive as `skipped`.
  -- The column exists now so turning scanning on is a code change and a backfill,
  -- not a migration against a table that is already carrying customer files.
  scan_status       stored_file_scan_status NOT NULL DEFAULT 'skipped',

  uploaded_by_user_id uuid REFERENCES "user" (id) ON DELETE SET NULL,
  uploaded_at         timestamptz(6) NOT NULL DEFAULT now(),

  CONSTRAINT stored_file_size_positive CHECK (size_bytes > 0)
);

CREATE UNIQUE INDEX stored_file_object_unique
  ON stored_file (blob_container, blob_name);

COMMENT ON TABLE stored_file IS
  'An object we stored. Owner-agnostic and reusable: quote, booking and claim attachments all point at this.';

-- ---------------------------------------------------------------------------

CREATE TABLE quote_document (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  quote_id        uuid NOT NULL REFERENCES quote (id) ON DELETE CASCADE,
  -- RESTRICT, not CASCADE: losing the link would orphan an object in the
  -- container with nothing left to say whose it was.
  stored_file_id  uuid NOT NULL REFERENCES stored_file (id) ON DELETE RESTRICT,

  -- Allow-listed portal code, never free text. v4 rule 6: document typing in
  -- CargoWise is manual and unvalidated, so only approved types are ever visible.
  document_type   varchar(40) NOT NULL,

  -- Who sent it. One table serves the safety data sheet a customer attaches and
  -- the priced PDF a branch answers with; without this they would be two tables
  -- differing only in who pressed the button.
  direction       quote_document_direction NOT NULL,

  -- False means absent from every customer surface, not hidden on one.
  customer_visible boolean NOT NULL DEFAULT true,

  position        integer NOT NULL,
  created_at      timestamptz(6) NOT NULL DEFAULT now(),
  updated_at      timestamptz(6) NOT NULL DEFAULT now(),

  CONSTRAINT quote_document_position_positive CHECK (position > 0)
);

CREATE UNIQUE INDEX quote_document_position_unique ON quote_document (quote_id, position);
CREATE UNIQUE INDEX quote_document_file_unique ON quote_document (quote_id, stored_file_id);
CREATE INDEX quote_document_quote_idx ON quote_document (quote_id);
CREATE INDEX quote_document_file_idx ON quote_document (stored_file_id);

COMMENT ON TABLE quote_document IS
  'A file attached to a quote, in either direction. customer_visible = false means absent from every customer surface.';
COMMENT ON COLUMN quote_document.direction IS
  'from_customer: papers supporting the request. to_customer: the branch answering with a document.';

-- ---------------------------------------------------------------------------
-- Row level security. Declared after both tables, because the read policy on
-- `stored_file` reaches through `quote_document`.
-- ---------------------------------------------------------------------------

-- Tenancy through the parent, matching quote_option, quote_equipment and
-- quote_dangerous_goods. A denormalised customer_group_id would be a second
-- source of truth that can drift from the quote's own.
ALTER TABLE quote_document ENABLE ROW LEVEL SECURITY;
ALTER TABLE quote_document FORCE ROW LEVEL SECURITY;

CREATE POLICY quote_document_tenant_isolation ON quote_document
  USING (
    EXISTS (
      SELECT 1 FROM quote q
      WHERE q.id = quote_document.quote_id
        AND (q.customer_group_id = app.current_group() OR app.is_internal())
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM quote q
      WHERE q.id = quote_document.quote_id
        AND (q.customer_group_id = app.current_group() OR app.is_internal())
    )
  );

GRANT SELECT, INSERT, UPDATE, DELETE ON quote_document TO portal_app;

-- A customer uploads their own papers, so this table is written by customer
-- sessions - but a stored file must only ever be READ through a link they can
-- see. Two policies, deliberately asymmetric.
ALTER TABLE stored_file ENABLE ROW LEVEL SECURITY;
ALTER TABLE stored_file FORCE ROW LEVEL SECURITY;

CREATE POLICY stored_file_read ON stored_file
  FOR SELECT
  USING (
    app.is_internal()
    OR EXISTS (
      SELECT 1
      FROM quote_document qd
      JOIN quote q ON q.id = qd.quote_id
      WHERE qd.stored_file_id = stored_file.id
        AND q.customer_group_id = app.current_group()
    )
  );

-- Update and delete stay internal: a customer may add a document and stop there.
CREATE POLICY stored_file_write ON stored_file
  FOR UPDATE
  USING (app.is_internal())
  WITH CHECK (app.is_internal());

CREATE POLICY stored_file_remove ON stored_file
  FOR DELETE
  USING (app.is_internal());

GRANT SELECT, INSERT, UPDATE, DELETE ON stored_file TO portal_app;

-- ---------------------------------------------------------------------------

/*
 * Records a stored file and returns its id.
 *
 * Through a function rather than a plain INSERT for the reason this schema has
 * met twice already: PostgreSQL applies the SELECT policy to `INSERT ...
 * RETURNING`, and at the moment of insert no `quote_document` row points at this
 * file yet - so the read policy above cannot be satisfied and the caller that
 * needs the id is refused. `app.record_outbound_message` exists for the same
 * reason.
 *
 * There is no tenancy check inside, and none is needed: a stored_file row is
 * inert. It is unreadable until a `quote_document` links it, and that insert is
 * checked against the quote's own policy. A row that never gets linked is
 * invisible to everybody, including whoever created it.
 */
CREATE FUNCTION app.record_stored_file(
  p_container    text,
  p_blob_name    text,
  p_filename     text,
  p_content_type text,
  p_size_bytes   integer,
  p_checksum     text,
  p_uploaded_by  uuid
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, app, pg_temp
AS $$
DECLARE
  v_id uuid;
BEGIN
  INSERT INTO stored_file (
    blob_container, blob_name, original_filename, content_type,
    size_bytes, checksum_sha256, uploaded_by_user_id
  )
  VALUES (
    p_container, p_blob_name, p_filename, p_content_type,
    p_size_bytes, p_checksum, p_uploaded_by
  )
  RETURNING stored_file.id INTO v_id;

  RETURN v_id;
END;
$$;

REVOKE EXECUTE ON FUNCTION app.record_stored_file(text, text, text, text, integer, text, uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION app.record_stored_file(text, text, text, text, integer, text, uuid) TO portal_app;

COMMENT ON FUNCTION app.record_stored_file(text, text, text, text, integer, text, uuid) IS
  'Inserts a stored_file and returns its id. Needed because INSERT ... RETURNING is subject to the SELECT policy, which cannot pass before the linking row exists.';
