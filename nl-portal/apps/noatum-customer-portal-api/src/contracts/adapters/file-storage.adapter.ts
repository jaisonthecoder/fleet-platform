/**
 * Where uploaded files actually live.
 *
 * A port for the same reason the CargoWise and email ports exist: business code
 * says "keep these bytes" and never learns whether that is a disk, a blob
 * container or something else. Swapping the transport is a provider binding.
 *
 * Deliberately NOT a signed-URL interface. Every download is streamed through the
 * API instead, so the permission check, the tenancy check and the audit record all
 * happen on the same request that serves the bytes. A signed URL hands out access
 * that outlives the check that granted it, which for a commercial document is the
 * wrong trade - and these are quotations and safety data sheets, not video.
 */
export abstract class FileStorageAdapter {
  /** False when no store is usable. Callers refuse the upload rather than pretend. */
  abstract isConfigured(): boolean;

  /** Writes the bytes. The caller owns the name; this never invents one. */
  abstract put(input: StoredFileInput): Promise<StoredFileHandle>;

  /** Null when the object is gone. A missing file is a state, not an exception. */
  abstract get(handle: StoredFileHandle): Promise<Buffer | null>;

  /** Idempotent: deleting something already absent is a success. */
  abstract delete(handle: StoredFileHandle): Promise<void>;
}

export interface StoredFileHandle {
  container: string;
  /**
   * The object name inside the container. Always generated by us - never a
   * client-supplied filename or path, which is how a traversal gets in.
   */
  blobName: string;
}

export interface StoredFileInput extends StoredFileHandle {
  content: Buffer;
  /** The verified type, not the one the browser claimed. */
  contentType: string;
}
